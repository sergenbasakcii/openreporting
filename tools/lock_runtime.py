"""Snapshot tested runtime versions and public PyPI wheel hashes; not a resolver.

Run in the tested Windows QA environment so the Windows-only tzdata root is included.
CI must install this snapshot on every supported Python/OS before acceptance.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import urllib.request

from runtime_requirements import inventory


def wheel_hashes(item):
    name, version = item
    if not re.fullmatch(r'[a-z0-9-]+',name) or not re.fullmatch(r'[0-9A-Za-z.+-]+',version):
        raise ValueError('Unexpected package identity')
    with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{version}/json',timeout=45) as response:
        data = json.load(response)
    hashes = sorted({row['digests']['sha256'] for row in data['urls'] if row['packagetype']=='bdist_wheel' and not row.get('yanked')})
    if not hashes or any(not re.fullmatch('[a-f0-9]{64}',value) for value in hashes):
        raise ValueError('Missing valid, non-yanked release wheel hashes')
    marker = '; platform_system == "Windows"' if name=='tzdata' else ''
    return f'{name}=={version}{marker} \\\n' + ' \\\n'.join(f'    --hash=sha256:{value}' for value in hashes) + '\n'


if __name__=='__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=Path('requirements-runtime.lock'))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    packages = inventory(root / 'pyproject.toml')
    if 'tzdata' not in packages:
        parser.error('Generate from the tested Windows QA snapshot; Windows tzdata must be present')
    with ThreadPoolExecutor(max_workers=6) as pool:
        rows = list(pool.map(wheel_hashes,packages.items()))
    header = ('# Tested runtime snapshot; generated by tools/lock_runtime.py.\n'
              '# Wheel-only: no source build fallback. No private index or local paths.\n'
              '# Build/test tooling is outside this lock; see docs/DEPENDENCY_LOCK.md.\n')
    args.output.write_text(header+'\n'.join(rows),encoding='utf8')
    print(f'Locked {len(packages)} runtime package versions with public release wheel SHA-256 hashes')
